/* An accessible tabbed view connects interests to real projects. */
const focusTabs = [...document.querySelectorAll('[data-focus]')];
function selectFocus(tab, moveFocus = false) {
  focusTabs.forEach(item => {
    const selected = item === tab;
    item.setAttribute('aria-selected', String(selected));
    item.tabIndex = selected ? 0 : -1;
    document.getElementById(item.getAttribute('aria-controls')).hidden = !selected;
  });
  if (moveFocus) tab.focus();
}
focusTabs.forEach((tab, index) => {
  tab.addEventListener('click', () => selectFocus(tab));
  tab.addEventListener('keydown', event => {
    let next;
    if (event.key === 'ArrowRight' || event.key === 'ArrowDown') next = (index + 1) % focusTabs.length;
    if (event.key === 'ArrowLeft' || event.key === 'ArrowUp') next = (index - 1 + focusTabs.length) % focusTabs.length;
    if (event.key === 'Home') next = 0;
    if (event.key === 'End') next = focusTabs.length - 1;
    if (next !== undefined) { event.preventDefault(); selectFocus(focusTabs[next], true); }
  });
});
